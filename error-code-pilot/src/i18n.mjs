export function catalogTexts(catalog) {
 const texts=new Set(),add=text=>{if(typeof text==='string'&&text.trim())texts.add(text);};
 for(const card of catalog.cards){add(card.message);for(const path of card.paths){
  add(path.symptom);add(path.part);path.action.forEach(add);path.verification.steps.forEach(add);add(path.ifNotFixed.message);add(path.qualifier);
 }}
 catalog.symptoms.forEach(s=>add(s.label_en));
 for(const resource of catalog.stepSupport||[]){add(resource.title);resource.lines.forEach(add);}
 return [...texts];
}

export function validateTranslations(catalog) {
 const missing=catalogTexts(catalog).filter(text=>typeof zh[text]!=='string'||!zh[text].trim());
 if(missing.length)throw new Error('Missing Chinese translation: '+missing.join('\n'));
}

export function translate(text,locale='en') {
 if(locale!=='zh-CN'||typeof text!=='string')return text;
 const source=text.trim();
 let value=zh[source];
 if(value===undefined&&source.includes(' · '))value=source.split(' · ').map(s=>translate(s,locale)).join(' · ');
 if(value===undefined&&/^ERROR /.test(source))value=source.replace(/^ERROR /,'错误码 ');
 if(value===undefined&&/^Guide model: /.test(source))value=source.replace(/^Guide model: /,'指导适用机型：');
 if(value===undefined&&/^Guide firmware: /.test(source))value=source.replace(/^Guide firmware: /,'指导适用固件：');
 if(value===undefined&&/^Quantity \d+$/.test(source))value=source.replace(/^Quantity /,'数量：');
 return value===undefined?text:text.replace(source,value);
}

export function installLanguageSwitch(doc=document) {
 const key='pie.language';let locale='en';
 try{if(sessionStorage.getItem(key)==='zh-CN')locale='zh-CN';}catch{/* Language remains usable without storage. */}
 const sources=new WeakMap(),attributes=new WeakMap();
 const ignored=node=>node.parentElement?.closest('script,style,textarea,.other-description,[data-no-translate]');
 const update=()=>{
  observer.disconnect();
  doc.documentElement.lang=locale;
  doc.title=translate('PIE Troubleshooter',locale);
  const walker=doc.createTreeWalker(doc.body,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()){
   const node=walker.currentNode;if(ignored(node)||!node.nodeValue.trim())continue;
   const previous=sources.get(node);
   const source=previous&&node.nodeValue===previous.output?previous.source:node.nodeValue;
   const output=translate(source,locale);sources.set(node,{source,output});
   if(node.nodeValue!==output)node.nodeValue=output;
  }
  for(const node of doc.body.querySelectorAll('[placeholder],[aria-label],[title],optgroup[label]')){
   if(node.closest('[data-no-translate]'))continue;
   const state=attributes.get(node)||{};
   for(const name of ['placeholder','aria-label','title','label'])if(node.hasAttribute(name)){
    const value=node.getAttribute(name),previous=state[name];
    const source=previous&&value===previous.output?previous.source:value,output=translate(source,locale);
    state[name]={source,output};if(value!==output)node.setAttribute(name,output);
   }
   attributes.set(node,state);
  }
  doc.getElementById('language-toggle').setAttribute('aria-pressed',String(locale==='zh-CN'));
  observer.observe(doc.body,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:['placeholder','aria-label','title','label']});
 };
 // Translate new render output without rebuilding controls, listeners, history,
 // open details or verification/outcome state. Originals never leave this tab.
 const observer=new MutationObserver(update);
 doc.getElementById('language-toggle').addEventListener('click',()=>{
  locale=locale==='en'?'zh-CN':'en';try{sessionStorage.setItem(key,locale);}catch{}
  update();
 });
 update();
 return {get locale(){return locale;},disconnect:()=>observer.disconnect()};
}
